"""Generate topics/r-api.dita from the API's OpenAPI document (FastAPI), so the reference can't drift.

python help/tools/openapi2dita.py           # write help/topics/r-api.dita
python help/tools/openapi2dita.py --check   # exit 1 if the committed topic is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

from lxml import etree
from lxml.builder import E

OUT = Path(__file__).resolve().parent.parent / "topics" / "r-api.dita"
DOCTYPE = '<!DOCTYPE reference PUBLIC "-//OASIS//DTD DITA Reference//EN" "reference.dtd">'
SIGNED_IN = {"start_run", "approve_rule", "reject_rule", "audit"}


def spec() -> dict[str, Any]:
    from api.main import GoogleVerifier, create_app
    from manifest.store import LocalBlobs, MemoryStore

    class NoLauncher:
        def run(self, env: dict[str, str]) -> str:
            return ""

    app = create_app(
        MemoryStore(), LocalBlobs(Path(".")), GoogleVerifier("", set()), NoLauncher(), maps=lambda: []
    )
    return app.openapi()


def generate(doc: dict[str, Any]) -> bytes:
    rows = []
    for path, ops in sorted(doc["paths"].items()):
        for method, op in sorted(ops.items()):
            name = op["operationId"].split("_api_")[0]
            access = "Signed-in writer" if name in SIGNED_IN else "Anyone"
            desc = (op.get("description") or op.get("summary") or "").strip().split("\n")[0]
            rows.append(E.row(E.entry(E.codeph(f"{method.upper()} {path}")), E.entry(access), E.entry(desc)))
    version = doc["info"]["version"]
    topic = E.reference(
        {"id": "r-api", "{http://www.w3.org/XML/1998/namespace}lang": "en-US"},
        E.title("API"),
        E.shortdesc(f"The MANIFEST API, version {version}: each endpoint and who may call it."),
        E.prolog(E.resourceid({"appname": "manifest-console", "appid": "api"})),
        E.refbody(
            E.section(E.p("Generated from the API's OpenAPI document. Writes need a Google ID token in an "
                          "Authorization: Bearer header.")),
            E.table({"frame": "all"}, E.title("Endpoints"), E.tgroup({"cols": "3"},
                E.thead(E.row(E.entry("Endpoint"), E.entry("Access"), E.entry("What it does"))),
                E.tbody(*rows))),
        ),
    )  # fmt: skip
    body = etree.tostring(topic, pretty_print=True, encoding="unicode")
    banner = "<!-- Generated by help/tools/openapi2dita.py from the API. Do not edit; edit the API. -->"
    return f'<?xml version="1.0" encoding="UTF-8"?>\n{DOCTYPE}\n{banner}\n{body}'.encode()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    data = generate(spec())
    if args.check:
        if not OUT.exists() or OUT.read_bytes() != data:
            print(f"{OUT} is out of date: run python help/tools/openapi2dita.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_bytes(data)
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
